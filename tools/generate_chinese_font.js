const fs = require('fs');

if (process.argv.length !== 5) {
  throw new Error('usage: node generate_chinese_font.js input.bdf map output.cpp');
}
const [, , bdfPath, mapPath, outputPath] = process.argv;
const map = fs.readFileSync(mapPath, 'utf8');
const wanted = new Set();
for (const raw of map.split(/\r?\n/)) {
  const token = raw.trim().replace(/,$/, '');
  if (!token) continue;
  if (token.includes('-')) {
    const [start, end] = token.split('-').map(Number);
    for (let code = start; code <= end; ++code) wanted.add(code);
  } else {
    wanted.add(parseInt(token.replace(/^\$/, ''), 16));
  }
}

const glyphs = [];
let current = null;
let inBitmap = false;
for (const line of fs.readFileSync(bdfPath, 'utf8').split(/\r?\n/)) {
  if (line.startsWith('STARTCHAR')) {
    current = { rows: [] };
    inBitmap = false;
  } else if (current && line.startsWith('ENCODING ')) {
    current.codepoint = Number(line.slice(9));
  } else if (current && line.startsWith('DWIDTH ')) {
    current.advance = Number(line.split(/\s+/)[1]);
  } else if (current && line.startsWith('BBX ')) {
    const parts = line.split(/\s+/).slice(1).map(Number);
    Object.assign(current, { width:parts[0], height:parts[1], xOffset:parts[2], yOffset:parts[3] });
  } else if (current && line.startsWith('BITMAP')) {
    inBitmap = true;
  } else if (current && line === 'ENDCHAR') {
    if (wanted.has(current.codepoint)) glyphs.push(current);
    current = null;
    inBitmap = false;
  } else if (current && inBitmap && /^[0-9A-Fa-f]+$/.test(line)) {
    current.rows.push(line.match(/../g).map(value => parseInt(value, 16)));
  }
}

glyphs.sort((a, b) => a.codepoint - b.codepoint);
const found = new Set(glyphs.map(glyph => glyph.codepoint));
const missing = [...wanted].filter(code => !found.has(code));
if (missing.length) throw new Error(`missing glyphs: ${missing.map(code => code.toString(16)).join(',')}`);

const bitmap = [];
const records = [];
for (const glyph of glyphs) {
  const rowBytes = Math.ceil(glyph.width / 8);
  const offset = bitmap.length;
  for (const row of glyph.rows) bitmap.push(...row.slice(0, rowBytes));
  records.push(`  {0x${glyph.codepoint.toString(16).padStart(4, '0')},${offset},${glyph.width},${glyph.height},${rowBytes},${glyph.advance},${glyph.xOffset},${glyph.yOffset}}`);
}

const bytes = [];
for (let index = 0; index < bitmap.length; index += 16) {
  bytes.push('  ' + bitmap.slice(index, index + 16).map(value => `0x${value.toString(16).padStart(2, '0')}`).join(','));
}
const output = `// Generated by tools/generate_chinese_font.js. Do not edit.\n` +
  `#include "watch_chinese_font.hpp"\n\nnamespace watch_font {\n` +
  `const Glyph glyphs[]={\n${records.join(',\n')}\n};\n` +
  `const std::size_t glyph_count=sizeof(glyphs)/sizeof(glyphs[0]);\n` +
  `const uint8_t bitmap[]={\n${bytes.join(',\n')}\n};\n}\n`;
fs.writeFileSync(outputPath, output);
console.log(`generated ${glyphs.length} glyphs, ${bitmap.length} bitmap bytes`);
